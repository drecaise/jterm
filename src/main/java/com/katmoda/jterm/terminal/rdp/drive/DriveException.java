package com.katmoda.jterm.terminal.rdp.drive;

/** A request refused with an NTSTATUS. Carries no stack trace: it is an answer, not a fault. */
final class DriveException extends Exception {

    final int status;

    DriveException(int status) {
        super(null, null, false, false);
        this.status = status;
    }
}
